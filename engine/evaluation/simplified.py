def is_endgame(board: chess.Board) -> bool:
    white_queens = len(board.pieces(chess.QUEEN, chess.WHITE))
    black_queens = len(board.pieces(chess.QUEEN, chess.BLACK))
    
    if white_queens == 0 and black_queens == 0:
        return True
        
    for color in [chess.WHITE, chess.BLACK]:
        if len(board.pieces(chess.QUEEN, color)) > 0:
            rooks = len(board.pieces(chess.ROOK, color))
            minors = len(board.pieces(chess.KNIGHT, color)) + len(board.pieces(chess.BISHOP, color))
            if rooks > 0 or minors > 1:
                return False
                
    return True

def evaluate(board: chess.Board) -> int:
    score = 0
    endgame = is_endgame(board)
    
    for sq, piece in board.piece_map().items():
        val = PIECE_VALUES[piece.piece_type]
        
        if piece.piece_type == chess.KING:
            pst = KING_END_GAME_PST if endgame else KING_MIDDLE_GAME_PST
        else:
            pst = PST_TABLES[piece.piece_type]
            
        pst_index = sq ^ 56 if piece.color == chess.WHITE else sq
        val += pst[pst_index]
        
        if piece.color == chess.WHITE:
            score += val
        else:
            score -= val
            
    return score